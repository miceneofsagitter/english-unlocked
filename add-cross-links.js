function makeEntry(lang, m, esOrFr) {
  const d = esOrFr === 'es' ? m.es : m.fr;
  return {
    language: lang,
    type: 'verb',
    verb: d.verb,
    emoji: m.emoji,
    simple: '',
    it: d.it,
    example_en: '',
    example_it: '',
    tags: m.tags,
    context_note: '',
    concept: m.concept
  };
}

function serializeVocab(varName, arr) {
  const entries = arr.map(e => '  ' + JSON.stringify(e)).join(',\n');
  return `const ${varName} = [\n${entries}\n];\n`;
}

let esAdded = 0, esUpdated = 0, frAdded = 0, frUpdated = 0;

for (const m of MAPPING) {
  // ES
  const esExist = ES_VOCAB.find(v => v.verb === m.es.verb && !v.concept);
  if (esExist) {
    esExist.concept = m.concept;
    esUpdated++;
  } else {
    const alreadyLinked = ES_VOCAB.find(v => v.concept === m.concept);
    if (!alreadyLinked) {
      ES_VOCAB.push(makeEntry('es', m, 'es'));
      esAdded++;
    }
  }
  // FR
  const frExist = FR_VOCAB.find(v => v.verb === m.fr.verb && !v.concept);
  if (frExist) {
    frExist.concept = m.concept;
    frUpdated++;
  } else {
    const alreadyLinked = FR_VOCAB.find(v => v.concept === m.concept);
    if (!alreadyLinked) {
      FR_VOCAB.push(makeEntry('fr', m, 'fr'));
      frAdded++;
    }
  }
}

fs.writeFileSync(path.join(DATA,'vocab-es.js'), serializeVocab('ES_VOCAB', ES_VOCAB));
fs.writeFileSync(path.join(DATA,'vocab-fr.js'), serializeVocab('FR_VOCAB', FR_VOCAB));

console.log(`ES: +${esAdded} nuovi, ~${esUpdated} aggiornati`);
console.log(`FR: +${frAdded} nuovi, ~${frUpdated} aggiornati`);
console.log('Scritto vocab-es.js e vocab-fr.js');
